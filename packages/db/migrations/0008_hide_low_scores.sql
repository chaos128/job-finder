-- 사람이 Supabase 대시보드 SQL Editor에서 실행한다. 조건부 update라 재실행해도 안전하다.
--
-- 50점 이하로 채점된 공고를 제외(hidden) 처리한다. 앞으로 들어오는 채점은
-- /api/scoring/results가 저장 직후 같은 규칙으로 처리하므로(AUTO_HIDE_MAX_SCORE),
-- 이 파일은 그 규칙을 도입하기 전에 쌓인 것을 한 번 맞추는 백필이다.
--
-- 경계는 이상이 아니라 이하다(<= 50). 실행 시점 운영 데이터에서 정확히 50점인 공고가
-- 10건이라 이 한 칸이 실제로 갈린다 — 채점완료 240건 중 108건(45%)이 대상이다.
--
-- 숨기기만 하고 풀지 않는다. 51점 이상을 hidden=false로 되돌리는 문장을 여기 같이
-- 두면, 손으로 제외해 둔 공고(실행 시점에 83점짜리 한 건이 그랬다)가 이 마이그레이션
-- 한 번에 되살아난다. 자동화가 사람의 결정을 덮어써서는 안 된다.
--
-- 제외된 공고는 사라지지 않는다 — 목록 맨 뒤로 내려가 회색으로 표시되고, 카드의
-- 되돌리기 버튼으로 언제든 올릴 수 있다. 알림 다이제스트는 minScore 70이라
-- 어차피 50점 이하를 고른 적이 없으므로 발송 동작은 달라지지 않는다.
update jobs j
   set hidden = true
  from scores s
 where s.job_id = j.id
   and s.status = 'ok'
   and s.total <= 50
   and j.hidden = false;
